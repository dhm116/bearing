// Command coregen writes core_gen.go from core.yaml, so the core module is
// compiled into Bearing rather than parsed at run time. go generate runs it
// from pkg/vocab: coregen core.yaml core_gen.go.
package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"os"
	"slices"
	"strings"

	"go.yaml.in/yaml/v3"

	modelv1alpha1 "bearing.example/gen/go/bearing/model/v1alpha1"
)

// coreNamespace is vocab.CoreNamespace, copied so coregen builds even when
// core_gen.go doesn't; a test keeps them equal.
const coreNamespace = "com.dougmccall.bearing.core"

// main panics on failure: go generate shows the message, and nothing else
// runs it.
func main() {
	if len(os.Args) != 3 {
		panic("usage: coregen core.yaml core_gen.go")
	}
	b, err := os.ReadFile(os.Args[1]) //nolint:gosec // the file go generate names
	if err != nil {
		panic(err)
	}
	src, err := render(b)
	if err != nil {
		panic(fmt.Sprintf("%s: %v", os.Args[1], err))
	}
	if err := os.WriteFile(os.Args[2], src, 0o644); err != nil { //nolint:gosec // a source file, world-readable like the rest
		panic(err)
	}
}

// module and term are core.yaml's shape; shapes are short enum names.
type module struct {
	Namespace string `yaml:"namespace"`
	Version   string `yaml:"version"`
	Terms     []term `yaml:"terms"`
}

type term struct {
	Name        string   `yaml:"name"`
	Is          string   `yaml:"is"`
	Type        string   `yaml:"type"`
	Cardinality string   `yaml:"cardinality"`
	Conflict    string   `yaml:"conflict"`
	Domain      []string `yaml:"domain"`
	Range       []string `yaml:"range"`
}

// render checks the core module and returns core_gen.go's source.
func render(yamlSrc []byte) ([]byte, error) {
	dec := yaml.NewDecoder(bytes.NewReader(yamlSrc))
	dec.KnownFields(true)
	var m module
	if err := dec.Decode(&m); err != nil {
		return nil, err
	}
	if m.Namespace != coreNamespace || m.Version == "" {
		return nil, fmt.Errorf("namespace must be %s and version set", coreNamespace)
	}
	kinds := map[string]bool{}
	for _, t := range m.Terms {
		if t.Is == "kind" {
			kinds[t.Name] = true
		}
	}
	var w strings.Builder
	fmt.Fprintf(&w, "// Code generated by coregen from core.yaml. DO NOT EDIT.\n\npackage vocab\n\n")
	fmt.Fprintf(&w, "import modelv1alpha1 \"bearing.example/gen/go/bearing/model/v1alpha1\"\n\n")
	fmt.Fprintf(&w, "var core = Module{Namespace: %q, Version: %q, Terms: []Term{\n", m.Namespace, m.Version)
	seen := map[string]bool{}
	for _, t := range m.Terms {
		if seen[t.Name] {
			return nil, fmt.Errorf("term %s: defined twice", t.Name)
		}
		seen[t.Name] = true
		for _, k := range slices.Concat(t.Domain, t.Range) {
			if !kinds[k] {
				return nil, fmt.Errorf("term %s: %q is not a kind of the module", t.Name, k)
			}
		}
		line, err := t.goLiteral()
		if err != nil {
			return nil, fmt.Errorf("term %s: %w", t.Name, err)
		}
		w.WriteString(line)
	}
	w.WriteString("}}\n")
	return format.Source([]byte(w.String()))
}

// goLiteral is the term as a Term literal; a kind has no shape, a relation
// no value type, and an attribute every shape field.
func (t term) goLiteral() (string, error) {
	is, err := enum("TermType", "TERM_TYPE_", t.Is, modelv1alpha1.TermType_value)
	if err != nil {
		return "", err
	}
	fields := []string{fmt.Sprintf("Name: %q", t.Name), "Type: " + is}
	if t.Is == "kind" {
		if t.Type != "" || t.Cardinality != "" || t.Conflict != "" || t.Domain != nil || t.Range != nil {
			return "", errors.New("a kind has no type, cardinality, conflict, domain or range")
		}
		return "{" + strings.Join(fields, ", ") + "},\n", nil
	}
	if (t.Is == "relation") != (t.Type == "") {
		return "", errors.New("an attribute needs a type, and a relation has none")
	}
	if t.Is == "attribute" && t.Range != nil {
		return "", errors.New("an attribute has no range")
	}
	if t.Type != "" {
		vt, err := enum("ValueType", "VALUE_TYPE_", t.Type, modelv1alpha1.ValueType_value)
		if err != nil {
			return "", err
		}
		fields = append(fields, "ValueType: "+vt)
	}
	card, err := enum("Cardinality", "CARDINALITY_", t.Cardinality, modelv1alpha1.Cardinality_value)
	if err != nil {
		return "", err
	}
	conflict, err := enum("ConflictPolicy", "CONFLICT_POLICY_", t.Conflict, modelv1alpha1.ConflictPolicy_value)
	if err != nil {
		return "", err
	}
	fields = append(fields, "Cardinality: "+card, "Conflict: "+conflict)
	for _, l := range []struct {
		field string
		kinds []string
	}{{"Domain", t.Domain}, {"Range", t.Range}} {
		if l.kinds != nil {
			fields = append(fields, fmt.Sprintf("%s: %#v", l.field, l.kinds))
		}
	}
	return "{" + strings.Join(fields, ", ") + "},\n", nil
}

// enum is the Go constant for a short enum name (string for
// VALUE_TYPE_STRING), refusing names the enum lacks and its zero value.
func enum(typ, prefix, short string, values map[string]int32) (string, error) {
	name := prefix + strings.ToUpper(short)
	if v, ok := values[name]; !ok || v == 0 {
		return "", fmt.Errorf("%q is not a %s", short, strings.ReplaceAll(strings.ToLower(strings.TrimSuffix(prefix, "_")), "_", " "))
	}
	return "modelv1alpha1." + typ + "_" + name, nil
}
