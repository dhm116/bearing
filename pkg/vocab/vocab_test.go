var update = flag.Bool("update", false, "rewrite core.yaml from today's registry")

// fromRegistry is the core module as today's registry holds it.
func fromRegistry(r *model.Registry) Module {
	m := Module{Namespace: CoreNamespace, Version: "1.0.0"}
	for _, k := range r.Kinds() {
		m.Terms = append(m.Terms, Term{Name: string(k), Is: IsKind})
	}
	enum := func(s, prefix string) string { return strings.ToLower(strings.TrimPrefix(s, prefix)) }
	kinds := func(ks []model.Kind) []string {
		var out []string
		for _, k := range ks {
			out = append(out, string(k))
		}
		return out
	}
	for _, p := range r.Predicates() {
		t := Term{
			Name: p.Name, Is: IsAttribute, Domain: kinds(p.Domain), Range: kinds(p.Range),
			Cardinality: enum(p.Cardinality.String(), "CARDINALITY_"), Conflict: enum(p.Conflict.String(), "CONFLICT_POLICY_"),
		}
		if p.Relation {
			t.Is = IsRelation
		} else {
			t.Type = enum(p.Type.String(), "VALUE_TYPE_")
		}
		m.Terms = append(m.Terms, t)
	}
	return m
}

func TestCoreModuleMatchesRegistry(t *testing.T) {
	want := fromRegistry(model.Core())
	if *update {
		b, err := yaml.Marshal(want)
		if err != nil {
			t.Fatal(err)
		}
		head := "# The core module (ADR 13): today's kinds and predicates, one to one.\n# Generated by go test ./pkg/vocab -update; edit the registry, not this file.\n"
		if err := os.WriteFile("core.yaml", append([]byte(head), b...), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	got := Core()
	if len(got.Terms) != len(want.Terms) {
		t.Fatalf("core.yaml has %d terms, the registry %d", len(got.Terms), len(want.Terms))
	}
	for i := range want.Terms {
		if got.Terms[i].Name != want.Terms[i].Name || got.Terms[i].Shape() != want.Terms[i].Shape() {
			t.Errorf("term %d: got %s %s, want %s %s", i, got.Terms[i].Name, got.Terms[i].Shape(), want.Terms[i].Name, want.Terms[i].Shape())
		}
	}
	// Every core kind loads into the registry under its bare name.
	for _, term := range got.Terms {
		if term.Is == IsKind && !model.Core().Valid(KindOf(Full(CoreNamespace, term.Name))) {
			t.Errorf("core kind %s is not in the registry", term.Name)
		}
	}
}

